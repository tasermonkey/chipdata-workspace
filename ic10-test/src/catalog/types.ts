/**
 * Generates the prefab types from a catalogue, so `sim().device(key, prefab, props)` is type-checked
 * and the editor shows each property's description, Read/Write and modes:
 * - generated/prefab-props.ts, shipped with the package: `GamePrefabProps`, the emulator's prefabs;
 * - a project's ic10-bench-env.d.ts (`ic10-bench catalog`): every prefab, the project's mods
 *   included, with the game's descriptions, as an augmentation of `ProjectPrefabs` (src/prefabs.ts).
 */
import type { Access, Catalog, CatalogPrefab } from "./catalog.ts";

/** The module a project's ic10-bench-env.d.ts augments. */
export const PREFABS_MODULE = "@tasermonkey/ic10-bench/prefabs";

const ACCESS: Record<Access, string> = { r: "read-only", w: "write-only", rw: "read, write" };

/** Text safe inside a JSDoc comment. */
function doc(text: string): string {
	return text.replace(/\*\//g, "*\\/").replace(/\s+/g, " ").trim();
}

function propertyDoc(catalog: Catalog, prefab: CatalogPrefab, name: string, access: Access): string {
	const parts = [catalog.logicTypes[name]?.text, `(${ACCESS[access]})`];
	if (name === "Mode" && prefab.modes.length) {
		parts.push(`Modes: ${prefab.modes.map((m, i) => `${i} ${m}`).filter((m) => !m.endsWith(" ")).join(", ")}.`);
	}
	return doc(parts.filter(Boolean).join(" "));
}

/** The interface's members, one prefab each, indented by `indent` tabs. */
function prefabMembers(catalog: Catalog, indent: number): string[] {
	const tab = "\t".repeat(indent);
	const lines: string[] = [];
	const prefabs = Object.values(catalog.prefabs).sort((a, b) => a.prefab.localeCompare(b.prefab));
	for (const prefab of prefabs) {
		const from = prefab.source === "mod" ? ", from a mod" : "";
		lines.push(`${tab}/** ${doc(prefab.title)} (hash ${prefab.hash}${from}) */`);
		lines.push(`${tab}${JSON.stringify(prefab.prefab)}: {`);
		for (const [name, access] of Object.entries(prefab.logic).sort(([a], [b]) => a.localeCompare(b))) {
			lines.push(`${tab}\t/** ${propertyDoc(catalog, prefab, name, access)} */`);
			lines.push(`${tab}\t${name}?: number;`);
		}
		lines.push(`${tab}};`);
	}
	return lines;
}

/** generated/prefab-props.ts: the packaged `GamePrefabProps`. */
export function prefabPropsSource(catalog: Catalog): string {
	return [
		"/* Generated by `npm run catalog:build` from the device catalogue. Do not edit. */",
		"",
		"/** Each of the emulator's prefabs' logic properties, as `sim().device()` takes them. */",
		"export interface GamePrefabProps {",
		...prefabMembers(catalog, 1),
		"}",
		"",
	].join("\n");
}

/** A project's ic10-bench-env.d.ts: every prefab in its catalogue, as `ProjectPrefabs`. */
export function projectTypesSource(catalog: Catalog): string {
	return [
		"/*",
		" * Generated by `ic10-bench catalog`. Do not edit, and don't commit it: it holds the game's text.",
		" * Gives `sim().device()` this project's prefabs, its mods' devices included, with descriptions.",
		" */",
		"export {};",
		"",
		`declare module ${JSON.stringify(PREFABS_MODULE)} {`,
		"\tinterface ProjectPrefabs {",
		...prefabMembers(catalog, 2),
		"\t}",
		"}",
		"",
	].join("\n");
}
